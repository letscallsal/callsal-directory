export function metroKey(metro: { city: string; region: string; country: string }): string {
  return `${metro.country}:${metro.region}:${metro.city}`.toLowerCase();
}

export function findMetro(city: string, region = "", country = ""): Metro | undefined {
  const name = city.trim().toLowerCase();
  if (!name) return undefined;
  const regionN = region.trim().toLowerCase();
  const countryN = country.trim().toLowerCase();
  const matches = METROS.filter((item) => item.city.toLowerCase() === name);
  if (!matches.length) {
    return METROS.find((item) => {
      const label = `${item.city} ${item.region}`.toLowerCase();
      const full = `${item.city}, ${item.region}`.toLowerCase();
      return label === name || full === name;
    });
  }
  const byCountry = countryN ? matches.filter((item) => item.country.toLowerCase() === countryN) : matches;
  const pool = byCountry.length ? byCountry : matches;
  if (regionN) {
    const hit = pool.find((item) => item.region.toLowerCase() === regionN);
    if (hit) return hit;
  }
  return pool.find((item) => item.popular) || pool[0];
}

export function metroLabel(metro: Metro, ambiguous = false): string {
  return ambiguous ? `${metro.city}, ${metro.region}` : metro.city;
}

export function labeledMetros(): Array<Metro & { label: string }> {
  const counts = new Map<string, number>();
  for (const metro of METROS) {
    const key = metro.city.toLowerCase();
    counts.set(key, (counts.get(key) || 0) + 1);
  }
  return METROS.map((metro) => ({
    ...metro,
    label: (counts.get(metro.city.toLowerCase()) || 0) > 1 ? `${metro.city}, ${metro.region}` : metro.city,
  }));
}
